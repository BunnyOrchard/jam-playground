"""Pull IAMM-1's sampled library out of LOF-1's ADPCM table.

The bytes stay the CC0 Versilian sets already encoded in
lof1/firmware/src/dsp/lof_samples.h. This does not edit that file.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "lof1" / "firmware" / "src" / "dsp" / "lof_samples.h"
DST = ROOT / "firmware" / "src" / "dsp" / "iam_samples.h"

# LOF set index, in the order the IAM engines walk after the oscillators.
WANT = [
    ("FMPI", 12),
    ("VIBES", 2),
    ("KALIMBA", 3),
    ("HARP", 14),
    ("UPBASS", 6),
    ("FLUTE", 9),
    ("SAX", 8),
    ("TPT", 7),
    ("HARPICA", 10),
    ("KIT", 11),
]


def main():
    text = SRC.read_text()
    sets = [tuple(int(x) for x in m.groups())
            for m in re.finditer(r"\{(\d+),\s*(\d+)\}", text.split("SMP_SET[", 1)[1].split(";", 1)[0])]
    zbody = text.split("SMP_ZONE[] = {", 1)[1].split("};", 1)[0]
    zones = []
    for m in re.finditer(
        r"\{(\d+)u,\s*(\d+)u,\s*(\d+)u,\s*(\d+)u,\s*(\d+)u,\s*([0-9.]+)f,\s*(-?\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+)\}",
        zbody,
    ):
        off, n, ls, le, rate, root, pred, idx, lo, hi, looped = m.groups()
        zones.append((int(off), int(n), int(ls), int(le), int(rate), float(root), int(pred), int(idx), int(lo), int(hi), int(looped)))
    data = [int(x) for x in re.findall(r"\d+", text.split("SMP_DATA[SMP_BYTES] = {", 1)[1].split("};", 1)[0])]
    if len(data) != 317920 or len(zones) != 63 or len(sets) != 18:
        sys.exit("lof_samples.h did not parse: %d bytes, %d zones, %d sets" % (len(data), len(zones), len(sets)))

    blob = []
    out_zones = []
    out_sets = []
    z0 = 0
    for name, si in WANT:
        a, nz = sets[si]
        zs = zones[a:a + nz]
        start = zs[0][0]
        end = zs[-1][0] + (zs[-1][1] + 1) // 2
        for i, z in enumerate(zs):
            span = (z[1] + 1) // 2
            expect = zs[i + 1][0] if i + 1 < len(zs) else end
            if z[0] + span != expect:
                sys.exit("%s zone %d is not packed (%d + %d != %d)" % (name, i, z[0], span, expect))
        chunk = data[start:end]
        base = len(blob)
        blob.extend(chunk)
        for z in zs:
            off, n, ls, le, rate, root, pred, idx, lo, hi, looped = z
            out_zones.append((off - start + base, n, ls, le, rate, root, pred, idx, lo, hi, looped))
        out_sets.append((z0, nz))
        z0 += nz
        print("%s %d bytes" % (name, len(chunk)))

    lines = [
        "/* generated by tools/iam_samples_gen.py from lof1/firmware/src/dsp/lof_samples.h */",
        "/* IMA ADPCM, 4-bit, low nibble first. CC0, Versilian Studios (VCSL and VSCO-2 CE). */",
        "/* Do not edit by hand. A new song does not draw these. Knob 1 walks into them. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "typedef struct { uint32_t off, n, ls, le, rate; float root; int16_t pred; uint8_t idx, lo, hi, looped; } iam_zone_t;",
        "typedef struct { uint16_t z0, nz; } iam_set_t;",
        "",
        "enum {",
        "    " + ", ".join("IAM_SMP_" + n for n, _ in WANT) + ", IAM_SMP_NSETS",
        "};",
        "#define IAM_SMP_BYTES %uu" % len(blob),
        "static const iam_set_t IAM_SET[IAM_SMP_NSETS] = {%s};" % ", ".join("{%d, %d}" % s for s in out_sets),
        "static const iam_zone_t IAM_ZONE[] = {",
    ]
    for z in out_zones:
        off, n, ls, le, rate, root, pred, idx, lo, hi, looped = z
        lines.append("    {%uu, %uu, %uu, %uu, %uu, %.3ff, %d, %d, %d, %d, %d}," % (off, n, ls, le, rate, root, pred, idx, lo, hi, looped))
    lines.append("};")
    lines.append("static const uint8_t IAM_SMP_DATA[IAM_SMP_BYTES] = {")
    for i in range(0, len(blob), 16):
        lines.append("    " + ",".join(str(b) for b in blob[i:i + 16]) + ",")
    lines.append("};")
    lines.append("")
    DST.write_text("\n".join(lines))
    print("wrote %s (%d bytes, %d zones)" % (DST, len(blob), len(out_zones)))


if __name__ == "__main__":
    main()
